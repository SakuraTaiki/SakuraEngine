#include "SceneFactory.h"

#include "GameScene.h"

// 処理概要: 担当機能で使用するオブジェクトまたはGPUリソースを生成する。
// 注意事項: 生成条件、所有者、破棄タイミングを明確にする。
std::unique_ptr<IScene> SceneFactory::CreateScene(const std::string& sceneName) {
    if (sceneName == "GAME") {
        return std::make_unique<GameScene>();
    }

    return nullptr;
}
